    NONLOCAL_PROCESSING_DISABLED = "NONLOCAL_PROCESSING_DISABLED"
    ENGINE_UNAVAILABLE = "ENGINE_UNAVAILABLE"
    ENGINE_TIMEOUT = "ENGINE_TIMEOUT"
    ENGINE_FAILED = "ENGINE_FAILED"
    OPERATION_FAILED = "OPERATION_FAILED"
